import { existsSync, lstatSync, mkdirSync, readFileSync, symlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { INSTALLED_VERSION, compareVersions, parseVersion } from "../../src/cli/version.js";
import { withMarker } from "../../src/render/marker.js";
import { expectedFiles, list, makeRepo, render } from "./repo.js";

const BODY = "@AGENTS.md\n";
const claude = (body: Record<string, any>, path = "CLAUDE.md") => body.files.find((f: any) => f.path === path);
const only = (extra = "") => makeRepo({ targets: "[claude-code]", modules: ["src/api"], extra });
const record = (dir: string) => JSON.parse(readFileSync(join(dir, ".liftoff/applied.json"), "utf8"));

describe("unedited generated files are refreshed, not treated as conflicts", () => {
  it("a file from an older generator version, body untouched: refreshed to the current marker", () => {
    const dir = only();
    writeFileSync(join(dir, "CLAUDE.md"), withMarker("0.0.1", BODY));
    const { exitCode, body } = render(dir);
    expect(exitCode).toBe(0);
    expect(claude(body)).toMatchObject({ action: "refreshed" });
    expect(readFileSync(join(dir, "CLAUDE.md"), "utf8")).toBe(expectedFiles(dir)["CLAUDE.md"]);
    expect(record(dir).conflicts).toEqual([]);
  });

  it("a config change that rewrites a body (constraints file) refreshes the Copilot file: the hash in the marker is what makes this work", () => {
    const dir = makeRepo({ targets: "[copilot]", modules: [], extra: "constraints:\n  file: CONSTRAINTS.md\n" });
    render(dir);
    const before = readFileSync(join(dir, ".github/copilot-instructions.md"), "utf8");
    writeFileSync(join(dir, "liftoff.yaml"), readFileSync(join(dir, "liftoff.yaml"), "utf8").replace("CONSTRAINTS.md", "docs/QUALITY.md"));
    const { body } = render(dir);
    expect(body.files[0]).toMatchObject({ path: ".github/copilot-instructions.md", action: "refreshed" });
    const after = readFileSync(join(dir, ".github/copilot-instructions.md"), "utf8");
    expect(after).not.toBe(before);
    expect(after).toContain("`docs/QUALITY.md`");
    expect(record(dir).conflicts).toEqual([]);
  });

  it("a refreshed file keeps its CRLF and BOM", () => {
    const dir = only();
    writeFileSync(join(dir, "CLAUDE.md"), "﻿" + withMarker("0.0.1", BODY).replace(/\n/g, "\r\n"));
    render(dir);
    const text = readFileSync(join(dir, "CLAUDE.md"), "utf8");
    expect(text.startsWith("﻿")).toBe(true);
    expect(text.replace(/^﻿/, "").replace(/\r\n/g, "\n")).toBe(expectedFiles(dir)["CLAUDE.md"]);
    expect(text.includes("\r\n")).toBe(true);
    expect(text.replace(/\r\n/g, "").includes("\n")).toBe(false);
  });

  it("the same version is not 'newer': an x.y marker equals x.y.0 and is refreshed when the body differs", () => {
    const dir = makeRepo({ targets: "[copilot]", modules: [], extra: "constraints:\n  file: docs/QUALITY.md\n" });
    const [major, minor] = INSTALLED_VERSION.split(".");
    // generated by "this version" (x.y) for another constraints file, body untouched
    mkdirSync(join(dir, ".github"), { recursive: true });
    writeFileSync(join(dir, ".github/copilot-instructions.md"), withMarker(`${major}.${minor}`, "Project instructions live in `AGENTS.md` at the repository root. Follow it and `CONSTRAINTS.md`.\n"));
    expect(render(dir).body.files[0].action).toBe("refreshed");
  });
});

describe("conflicts are reported, never written", () => {
  const sameText = (dir: string, path: string) => readFileSync(join(dir, path), "utf8");

  it("no marker at all: reason no-marker", () => {
    const dir = only();
    writeFileSync(join(dir, "CLAUDE.md"), "# my rules\n");
    const { exitCode, body } = render(dir);
    expect(exitCode).toBe(0);
    expect(claude(body)).toMatchObject({ action: "conflict", reason: "no-marker", proposed: expectedFiles(dir)["CLAUDE.md"] });
    expect(sameText(dir, "CLAUDE.md")).toBe("# my rules\n");
    expect(record(dir).conflicts).toEqual(["CLAUDE.md"]);
  });

  it("a marker whose hash no longer matches the body: reason hand-edited", () => {
    const dir = only();
    const edited = withMarker("0.0.1", BODY) + "One more rule I added.\n";
    writeFileSync(join(dir, "CLAUDE.md"), edited);
    expect(claude(render(dir).body)).toMatchObject({ action: "conflict", reason: "hand-edited" });
    expect(sameText(dir, "CLAUDE.md")).toBe(edited);
  });

  it.each([["99.0.0"], ["0.99"], ["1.0.0"], ["0.1.0-beta.1"], ["weird"]])(
    "unedited but written by generator %s (newer or unreadable): reason newer-generator, not refreshed",
    (version) => {
      const dir = only();
      const text = withMarker(version, "Some other body from another LiftOff.\n");
      writeFileSync(join(dir, "CLAUDE.md"), text);
      expect(claude(render(dir).body)).toMatchObject({ action: "conflict", reason: "newer-generator" });
      expect(sameText(dir, "CLAUDE.md")).toBe(text);
    },
  );

  it("a file that already equals the render is unchanged whatever its version marker says", () => {
    const dir = only();
    render(dir);
    expect(render(dir).body.files.every((f: any) => f.action === "unchanged")).toBe(true);
  });
});

describe("--overwrite replaces the whole file, per path", () => {
  it.each([
    ["no-marker", () => "# my rules\n"],
    ["hand-edited", () => withMarker("0.0.1", BODY) + "extra\n"],
    ["newer-generator", () => withMarker("99.0.0", "other\n")],
  ])("resolves a %s conflict and clears it from the record", (_reason, make) => {
    const dir = only();
    writeFileSync(join(dir, "CLAUDE.md"), make());
    const { exitCode, body } = render(dir, "--overwrite", "CLAUDE.md");
    expect(exitCode).toBe(0);
    expect(claude(body)).toMatchObject({ action: "refreshed" });
    expect(readFileSync(join(dir, "CLAUDE.md"), "utf8")).toBe(expectedFiles(dir)["CLAUDE.md"]);
    expect(record(dir).conflicts).toEqual([]);
  });

  it("only the named files are replaced; the others stay conflicts", () => {
    const dir = only();
    writeFileSync(join(dir, "CLAUDE.md"), "# root\n");
    mkdirSync(join(dir, "src/api"), { recursive: true });
    writeFileSync(join(dir, "src/api/CLAUDE.md"), "# module\n");
    const { body } = render(dir, "--overwrite", "CLAUDE.md");
    expect(claude(body)).toMatchObject({ action: "refreshed" });
    expect(claude(body, "src/api/CLAUDE.md")).toMatchObject({ action: "conflict", reason: "no-marker" });
    expect(readFileSync(join(dir, "src/api/CLAUDE.md"), "utf8")).toBe("# module\n");
    expect(record(dir).conflicts).toEqual(["src/api/CLAUDE.md"]);
  });

  it("several --overwrite in one call (a batch), repeated or with =", () => {
    const dir = only();
    writeFileSync(join(dir, "CLAUDE.md"), "# root\n");
    mkdirSync(join(dir, "src/api"), { recursive: true });
    writeFileSync(join(dir, "src/api/CLAUDE.md"), "# module\n");
    const { body } = render(dir, "--overwrite", "CLAUDE.md", "--overwrite=src/api/CLAUDE.md");
    expect(body.files.map((f: any) => f.action)).toEqual(["refreshed", "refreshed"]);
    expect(record(dir).conflicts).toEqual([]);
  });

  it("arguments are normalized like generated paths: ./CLAUDE.md and backslashes", () => {
    const dir = only();
    writeFileSync(join(dir, "CLAUDE.md"), "# root\n");
    mkdirSync(join(dir, "src/api"), { recursive: true });
    writeFileSync(join(dir, "src/api/CLAUDE.md"), "# module\n");
    const { body } = render(dir, "--overwrite", "./CLAUDE.md", "--overwrite", "src\\api\\CLAUDE.md");
    expect(body.files.map((f: any) => f.action)).toEqual(["refreshed", "refreshed"]);
  });

  it("keeps the existing line endings of the file it replaces", () => {
    const dir = only();
    writeFileSync(join(dir, "CLAUDE.md"), "# root\r\n# rules\r\n");
    render(dir, "--overwrite", "CLAUDE.md");
    const text = readFileSync(join(dir, "CLAUDE.md"), "utf8");
    expect(text.replace(/\r\n/g, "\n")).toBe(expectedFiles(dir)["CLAUDE.md"]);
    expect(text.includes("\r\n")).toBe(true);
  });

  it("naming a file that is not in conflict does nothing", () => {
    const dir = only();
    render(dir);
    const { exitCode, body } = render(dir, "--overwrite", "CLAUDE.md");
    expect(exitCode).toBe(0);
    expect(body.files.every((f: any) => f.action === "unchanged")).toBe(true);
    expect(body.notices).toEqual([]);
  });

  it.each([["CLAUDE.mdd"], ["/abs/CLAUDE.md"], ["../CLAUDE.md"], ["src/CLAUDE.md"], ["AGENTS.md"], [""]])(
    "%j names no generated file: usage error (exit 2) before anything is written",
    (arg) => {
      const dir = only();
      const { exitCode, body } = render(dir, "--overwrite", arg);
      expect(exitCode).toBe(2);
      expect(body.errors[0].code).toBe("usage");
      expect(body.errors[0].message).toMatch(/--overwrite names no file render writes/);
      expect(existsSync(join(dir, ".liftoff"))).toBe(false);
      expect(list(dir).filter((p) => p.endsWith("CLAUDE.md"))).toEqual([]);
    },
  );

  it("one bad argument among good ones rejects the whole call", () => {
    const dir = only();
    writeFileSync(join(dir, "CLAUDE.md"), "# root\n");
    const { exitCode } = render(dir, "--overwrite", "CLAUDE.md", "--overwrite", "nope.md");
    expect(exitCode).toBe(2);
    expect(readFileSync(join(dir, "CLAUDE.md"), "utf8")).toBe("# root\n");
  });
});

describe("symlinks and directories", () => {
  it("CLAUDE.md -> AGENTS.md is left alone: skipped-symlink, nothing written, not a conflict", () => {
    const dir = only();
    symlinkSync("AGENTS.md", join(dir, "CLAUDE.md"));
    const { exitCode, body } = render(dir);
    expect(exitCode).toBe(0);
    expect(claude(body)).toMatchObject({ action: "skipped-symlink" });
    expect(lstatSync(join(dir, "CLAUDE.md")).isSymbolicLink()).toBe(true);
    expect(readFileSync(join(dir, "AGENTS.md"), "utf8")).toBe("# rules\n");
    expect(record(dir).conflicts).toEqual([]);
    expect(record(dir).files).toContain("CLAUDE.md");
  });

  it("also for a module CLAUDE.md, and through an AGENTS.md that is itself a symlink to an ordinary file", () => {
    const dir = makeRepo({ targets: "[claude-code]", modules: ["src/api"], agentsMd: ["AGENTS.md"] });
    mkdirSync(join(dir, "src/api"), { recursive: true });
    writeFileSync(join(dir, "src/api/RULES.md"), "# module rules\n");
    symlinkSync("RULES.md", join(dir, "src/api/AGENTS.md"));
    symlinkSync("AGENTS.md", join(dir, "src/api/CLAUDE.md"));
    expect(claude(render(dir).body, "src/api/CLAUDE.md")).toMatchObject({ action: "skipped-symlink" });
  });

  it("a symlink to anything else is a conflict (symlink) and is never written through, even with --overwrite", () => {
    const dir = only();
    writeFileSync(join(dir, "OTHER.md"), "# other\n");
    symlinkSync("OTHER.md", join(dir, "CLAUDE.md"));
    const { exitCode, body } = render(dir, "--overwrite", "CLAUDE.md");
    expect(exitCode).toBe(0);
    expect(claude(body)).toMatchObject({ action: "conflict", reason: "symlink" });
    expect(readFileSync(join(dir, "OTHER.md"), "utf8")).toBe("# other\n");
    expect(lstatSync(join(dir, "CLAUDE.md")).isSymbolicLink()).toBe(true);
    expect(body.notices).toEqual(["CLAUDE.md: --overwrite does not apply to a symlink"]);
  });

  it("the Copilot file as a symlink to AGENTS.md is a conflict, not skipped: only CLAUDE.md gets the pass", () => {
    const dir = makeRepo({ targets: "[copilot]", modules: [] });
    mkdirSync(join(dir, ".github"));
    symlinkSync("../AGENTS.md", join(dir, ".github/copilot-instructions.md"));
    expect(render(dir).body.files[0]).toMatchObject({ action: "conflict", reason: "symlink" });
  });

  it("a directory is a not-regular conflict that --overwrite cannot touch", () => {
    const dir = only();
    mkdirSync(join(dir, "CLAUDE.md"));
    const { body } = render(dir, "--overwrite", "CLAUDE.md");
    expect(claude(body)).toMatchObject({ action: "conflict", reason: "not-regular" });
    expect(body.notices).toEqual(["CLAUDE.md: --overwrite does not apply to a not-regular"]);
    expect(lstatSync(join(dir, "CLAUDE.md")).isDirectory()).toBe(true);
  });
});

describe("version comparison", () => {
  it.each([
    ["1.4", "1.4.0", 0],
    ["1.10", "1.9", 1],
    ["0.1.0", "0.1.1", -1],
    ["2.0", "1.99.99", 1],
    ["0.0.1", "0.1", -1],
  ])("compareVersions(%s, %s) has the sign of %i", (a, b, sign) => {
    expect(Math.sign(compareVersions(a, b)!)).toBe(sign);
  });

  it.each(["", "1", "1.2.3.4", "1.x", "v1.2", "1.2.3-beta", " 1.2"])("%j is unparseable", (v) => {
    expect(parseVersion(v)).toBeUndefined();
    expect(compareVersions(v, "1.0")).toBeUndefined();
    expect(compareVersions("1.0", v)).toBeUndefined();
  });
});
