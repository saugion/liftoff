import { describe, expect, it } from "vitest";
import { type Config, validateConfig } from "../../src/config/index.js";
import { isUnedited, parseMarker } from "../../src/render/marker.js";
import { renderAgentFiles } from "../../src/render/index.js";
import { GOLDEN_VERSION, asMap, cases, expectedFiles, loadConfig, render } from "./golden.js";

describe("golden: every render case (Claude, Copilot, both)", () => {
  it.each(cases())("%s renders exactly the expected files", (name) => {
    expect(asMap(render(loadConfig(name)))).toEqual(expectedFiles(name));
  });

  it("covers the three target combinations", () => {
    const targets = cases().map((c) => loadConfig(c).agents.targets.join("+"));
    expect(targets).toEqual(expect.arrayContaining(["claude-code", "copilot", "claude-code+copilot"]));
  });
});

const config = (targets: string[], extra: Record<string, unknown> = {}): Config => {
  const r = validateConfig({ liftoff: 1, plugin: { version: "0.1" }, project: { name: "a", kind: "new" }, agents: { targets }, ...extra });
  if (!r.ok) throw new Error(JSON.stringify(r.errors));
  return r.value;
};

describe("Copilot file", () => {
  it("is .github/copilot-instructions.md: marker, pointer, constraints path, nothing else", () => {
    const [file] = render(config(["copilot"]));
    expect(file!.path).toBe(".github/copilot-instructions.md");
    expect(file!.agent).toBe("copilot");
    expect(file!.content.split("\n")).toEqual([
      expect.stringMatching(/^<!-- generated by liftoff render 0\.1\.0; body-sha256:[0-9a-f]{64}; edit AGENTS\.md instead -->$/),
      "Project instructions live in `AGENTS.md` at the repository root. Follow it and `CONSTRAINTS.md`.",
      "",
    ]);
    expect(isUnedited(file!.content)).toBe(true);
  });

  it("holds no stack, module list or rules: those live in AGENTS.md", () => {
    const body = parseMarker(
      render(
        config(["copilot"], {
          stack: { languages: ["typescript"], frameworks: ["nestjs"] },
          modules: { items: [{ id: "api-layer", path: "src/api", description: "HTTP layer" }] },
        }),
      )[0]!.content,
    )!.body;
    for (const leaked of ["typescript", "nestjs", "api-layer", "src/api", "HTTP layer"]) expect(body).not.toContain(leaked);
  });

  it("the constraints path comes from the config, defaulting when the section is absent", () => {
    const body = (extra?: Record<string, unknown>) => parseMarker(render(config(["copilot"], extra))[0]!.content)!.body;
    expect(body()).toContain("`CONSTRAINTS.md`");
    expect(body({ constraints: {} })).toContain("`CONSTRAINTS.md`");
    expect(body({ constraints: { file: "docs/QUALITY.md" } })).toContain("`docs/QUALITY.md`");
    expect(body({ constraints: { file: "./docs\\QUALITY.md" } })).toContain("`docs/QUALITY.md`");
  });

  it("does not depend on modules at all (same file with and without)", () => {
    const withModules = asMap(render(config(["copilot"], { modules: { items: [{ id: "a", path: "a" }] } })));
    expect(withModules).toEqual(asMap(render(config(["copilot"]))));
  });

  it("the generator version changes only the marker line", () => {
    const a = render(config(["copilot"]), "0.1.0")[0]!.content.split("\n");
    const b = render(config(["copilot"]), "3.0.0")[0]!.content.split("\n");
    expect(a[0]).not.toBe(b[0]);
    expect(a.slice(1)).toEqual(b.slice(1));
    expect(parseMarker(a.join("\n"))!.hash).toBe(parseMarker(b.join("\n"))!.hash);
  });

  it("a claude-only config renders no Copilot file", () => {
    expect(render(config(["claude-code"])).some((f) => f.agent === "copilot")).toBe(false);
  });
});

describe("both targets", () => {
  const files = render(config(["claude-code", "copilot"], { modules: { items: [{ id: "a", path: "src/a" }, { id: "b", path: "lib/b" }] } }));

  it("renders all files sorted by path: .github first, then CLAUDE.md, then the modules", () => {
    expect(files.map((f) => f.path)).toEqual([".github/copilot-instructions.md", "CLAUDE.md", "lib/b/CLAUDE.md", "src/a/CLAUDE.md"]);
  });

  it("the order of targets in the config does not change the output", () => {
    const mods = { modules: { items: [{ id: "a", path: "src/a" }, { id: "b", path: "lib/b" }] } };
    expect(render(config(["copilot", "claude-code"], mods))).toEqual(files);
  });

  it("same config twice is byte-identical", () => {
    expect(JSON.stringify(render(config(["claude-code", "copilot"])))).toBe(JSON.stringify(render(config(["claude-code", "copilot"]))));
  });

  it("every file starts with the marker and ends with a single newline", () => {
    for (const f of files) {
      expect(parseMarker(f.content), f.path).toBeDefined();
      expect(f.content.endsWith("\n") && !f.content.endsWith("\n\n"), f.path).toBe(true);
      expect(f.content.includes("\r"), f.path).toBe(false);
    }
  });
});

describe("render errors that only matter to Copilot", () => {
  const errors = (extra: Record<string, unknown>, targets = ["copilot"]) => {
    // The schema accepts "." and backticks in a path, so render has to catch them.
    const r = renderAgentFiles(config(targets, extra), { generatorVersion: GOLDEN_VERSION });
    return r.ok ? [] : r.errors;
  };

  // (A line break in the path never reaches render: the schema's relativePath pattern already rejects it.)
  it.each([".", "./", "`x`.md"])("constraints file %j is rejected at /constraints/file", (file) => {
    expect(errors({ constraints: { file } }).map((e) => e.path)).toEqual(["/constraints/file"]);
  });

  it("the same value is fine when Copilot is not a target (no file embeds it)", () => {
    expect(errors({ constraints: { file: "." } }, ["claude-code"])).toEqual([]);
  });

  it("reports module and constraints problems together", () => {
    const e = errors({ modules: { items: [{ id: "a", path: "." }] }, constraints: { file: "." } });
    expect(e.map((x) => x.path)).toEqual(["/modules/items/0/path", "/constraints/file"]);
  });
});

describe("marker version guard", () => {
  it.each(["", "1.0 0", "1;0", "a b"])("a generator version of %j throws (programmer error), not a silent bad marker", (v) => {
    expect(() => renderAgentFiles(config(["copilot"]), { generatorVersion: v })).toThrow(/invalid generator version/);
  });
});
