import { describe, expect, it } from "vitest";
import { bodyHash, isUnedited, normalizeEol, parseMarker, withMarker } from "../../src/render/marker.js";

describe("marker", () => {
  const text = withMarker("1.4.2", "@AGENTS.md\n");

  it("is the first line and carries the generator version and the body hash", () => {
    const [first, ...rest] = text.split("\n");
    expect(first).toBe(`<!-- generated by liftoff render 1.4.2; body-sha256:${bodyHash("@AGENTS.md\n")}; edit AGENTS.md instead -->`);
    expect(rest.join("\n")).toBe("@AGENTS.md\n");
  });

  it("bodyHash is the hex sha256 of the LF-normalized body (known vector)", () => {
    expect(bodyHash("@AGENTS.md\n")).toBe("336cc4fbf19beaada7ccf9986414fa91851a8d7a07dfb3ccbe800a69eed0ab49");
    expect(bodyHash("@AGENTS.md\r\n")).toBe(bodyHash("@AGENTS.md\n"));
    expect(bodyHash("﻿@AGENTS.md\n")).toBe(bodyHash("@AGENTS.md\n"));
  });

  it("parseMarker round-trips and returns the LF body", () => {
    expect(parseMarker(text)).toEqual({ version: "1.4.2", hash: bodyHash("@AGENTS.md\n"), body: "@AGENTS.md\n" });
  });

  it("an unedited file is unedited whatever its line endings or BOM", () => {
    expect(isUnedited(text)).toBe(true);
    expect(isUnedited(text.replace(/\n/g, "\r\n"))).toBe(true);
    expect(isUnedited("﻿" + text)).toBe(true);
  });

  it("any body edit makes it hand-edited, the marker line alone changing does not", () => {
    expect(isUnedited(text + "extra rule\n")).toBe(false);
    expect(isUnedited(text.replace("@AGENTS.md", "@OTHER.md"))).toBe(false);
    expect(isUnedited(text.replace("1.4.2", "9.9.9"))).toBe(true);
  });

  it("no marker, a malformed marker or an empty file is not parsed", () => {
    for (const t of ["", "@AGENTS.md\n", "<!-- generated by liftoff render; body-sha256:abc -->\n", `\n${text}`]) {
      expect(parseMarker(t), JSON.stringify(t)).toBeUndefined();
      expect(isUnedited(t)).toBe(false);
    }
  });

  it("a marker with a tampered hash is hand-edited", () => {
    expect(isUnedited(text.replace(/body-sha256:[0-9a-f]{2}/, "body-sha256:00"))).toBe(false);
  });

  it("normalizeEol strips a BOM and CRLF only", () => {
    expect(normalizeEol("﻿a\r\nb\rc\n")).toBe("a\nb\rc\n");
  });
});
