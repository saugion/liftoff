import { describe, expect, it } from "vitest";
import { type Config, validateConfig } from "../../src/config/index.js";
import { bodyHash, isUnedited, parseMarker } from "../../src/render/marker.js";
import { normalizeModulePath, renderAgentFiles } from "../../src/render/index.js";
import { GOLDEN_VERSION, asMap, cases, expectedFiles, loadConfig, render } from "./golden.js";

const claudeCases = cases().filter((c) => c.startsWith("claude-"));

describe("golden: Claude Code renderer", () => {
  it("has golden cases to run", () => expect(claudeCases.length).toBeGreaterThanOrEqual(3));

  it.each(claudeCases)("%s renders exactly the expected files", (name) => {
    expect(asMap(render(loadConfig(name)))).toEqual(expectedFiles(name));
  });
});

const config = (extra: Record<string, unknown> = {}, targets: string[] = ["claude-code"]): Config => {
  const r = validateConfig({ liftoff: 1, plugin: { version: "0.1" }, project: { name: "a", kind: "new" }, agents: { targets }, ...extra });
  if (!r.ok) throw new Error(JSON.stringify(r.errors));
  return r.value;
};
const modules = (...paths: string[]) => ({ modules: { items: paths.map((path, i) => ({ id: `m${i}`, path })) } });
const deepFreeze = <T>(o: T): T => {
  if (o !== null && typeof o === "object") {
    Object.values(o).forEach(deepFreeze);
    Object.freeze(o);
  }
  return o;
};

describe("Claude Code files", () => {
  it("a root CLAUDE.md plus one per module, sorted by path", () => {
    const files = render(config(modules("src/web", "src/api", "apps/x")));
    expect(files.map((f) => f.path)).toEqual(["CLAUDE.md", "apps/x/CLAUDE.md", "src/api/CLAUDE.md", "src/web/CLAUDE.md"]);
    expect(files.every((f) => f.agent === "claude-code")).toBe(true);
  });

  it("no modules (absent or empty) gives only the root file", () => {
    expect(render(config()).map((f) => f.path)).toEqual(["CLAUDE.md"]);
    expect(render(config({ modules: {} })).map((f) => f.path)).toEqual(["CLAUDE.md"]);
  });

  it("every file is marker + the import, LF, one trailing newline, import exactly once", () => {
    for (const f of render(config(modules("a", "b/c")))) {
      expect(f.content.includes("\r")).toBe(false);
      expect(f.content.endsWith("\n") && !f.content.endsWith("\n\n")).toBe(true);
      expect(f.content.split("\n")).toHaveLength(3); // marker, import, "" after the last newline
      expect(f.content.split("@AGENTS.md").length - 1).toBe(1);
      expect(f.content.split("\n")[0]).toMatch(/^<!-- generated by liftoff render /);
    }
  });

  it("the marker hash matches the body (CRLF-normalized), so the file counts as unedited", () => {
    for (const f of render(config(modules("a")))) {
      const m = parseMarker(f.content)!;
      expect(m.hash).toBe(bodyHash("@AGENTS.md\n"));
      expect(isUnedited(f.content)).toBe(true);
      expect(isUnedited(f.content.replace(/\n/g, "\r\n"))).toBe(true);
    }
  });

  it("the generator version changes only the marker line, never the body hash", () => {
    const a = render(config(modules("a")), "0.1.0");
    const b = render(config(modules("a")), "0.2.7");
    expect(a.map((f) => f.path)).toEqual(b.map((f) => f.path));
    for (const [i, f] of a.entries()) {
      expect(parseMarker(f.content)!.version).toBe("0.1.0");
      expect(parseMarker(b[i]!.content)!.version).toBe("0.2.7");
      expect(parseMarker(f.content)!.hash).toBe(parseMarker(b[i]!.content)!.hash);
      expect(f.content.split("\n").slice(1)).toEqual(b[i]!.content.split("\n").slice(1));
    }
  });

  it("is deterministic and does not mutate its input", () => {
    const c = deepFreeze(config(modules("src/api", "src/web")));
    expect(render(c)).toEqual(render(c));
  });

  it("does not depend on the config's other sections (stack, constraints)", () => {
    const plain = asMap(render(config(modules("a"))));
    const rich = asMap(render(config({ ...modules("a"), stack: { languages: ["ts"] }, constraints: { file: "docs/C.md", required: true } })));
    expect(rich).toEqual(plain);
  });

  it("a copilot-only config renders no Claude files", () => {
    expect(render(config(modules("a"), ["copilot"])).filter((f) => f.agent === "claude-code")).toEqual([]);
  });
});

describe("module path normalization", () => {
  it.each([
    ["src/api", "src/api"],
    ["src/api/", "src/api"],
    ["./src/api", "src/api"],
    ["src//api", "src/api"],
    ["src/./api", "src/api"],
    ["libs\\core\\", "libs/core"],
    ["./.", ""],
    [".", ""],
    ["", ""],
  ])("%j -> %j", (input, output) => {
    expect(normalizeModulePath(input)).toBe(output);
  });
});

describe("module path errors", () => {
  const errorsFor = (...paths: string[]) => {
    const r = renderAgentFiles(config(modules(...paths)), { generatorVersion: GOLDEN_VERSION });
    return r.ok ? [] : r.errors;
  };

  it.each([".", "./", "./."])("path %j is the repo root: error at that item", (p) => {
    const errors = errorsFor("src/a", p);
    expect(errors.map((e) => e.path)).toEqual(["/modules/items/1/path"]);
    expect(errors[0]!.message).toMatch(/repo root/);
  });

  it("two modules with the same normalized path: error at the later one, naming the first", () => {
    const errors = errorsFor("src/api", "src/web", "./src/api/");
    expect(errors).toHaveLength(1);
    expect(errors[0]!.path).toBe("/modules/items/2/path");
    expect(errors[0]!.message).toContain("'m2'");
    expect(errors[0]!.message).toContain("'m0'");
  });

  it("reports every problem, and renders nothing when there is one", () => {
    const r = renderAgentFiles(config(modules(".", "a", "a/")), { generatorVersion: GOLDEN_VERSION });
    expect(!r.ok && r.errors.map((e) => e.path)).toEqual(["/modules/items/0/path", "/modules/items/2/path"]);
  });

  it("errors are reported even for a copilot-only config (they are config problems)", () => {
    const r = renderAgentFiles(config(modules("."), ["copilot"]), { generatorVersion: GOLDEN_VERSION });
    expect(r.ok).toBe(false);
  });
});
