import { existsSync, mkdirSync, readFileSync, symlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { run } from "../../src/cli/main.js";
import { tempDir } from "../helpers.js";
import { list, makeRepo } from "../cli/repo.js";

const init = (dir: string, ...extra: string[]) => {
  const r = run(["brain-init", "--root", dir, ...extra], "/");
  return { exitCode: r.exitCode, body: JSON.parse(r.stdout) as Record<string, any> };
};
const repo = (extra = "brain: {}\n", targets = "[claude-code]") => makeRepo({ targets, modules: [], pluginVersion: "0.4", extra });

const SCAFFOLD = [
  ".liftoff/.gitignore",
  ".liftoff/brain/hot.md",
  ".liftoff/brain/notes/.gitkeep",
  "brain/README.md",
  "brain/hot.md",
  "brain/index.md",
  "brain/log/.gitkeep",
  "brain/raw/.gitkeep",
  "brain/wiki/.gitkeep",
];

describe("brain-init", () => {
  it("a config without `brain` is no-brain, exit 1, nothing written", () => {
    const dir = repo("");
    const { exitCode, body } = init(dir, "--write");
    expect(exitCode).toBe(1);
    expect(body.errors[0].code).toBe("no-brain");
    expect(body.errors[0].message).toContain("Brain skill, Setup");
    expect(list(dir)).toEqual(["AGENTS.md", "liftoff.yaml"]);
  });

  it("a dry run lists what it would create and writes nothing", () => {
    const dir = repo();
    const { exitCode, body } = init(dir);
    expect(exitCode).toBe(0);
    expect(body.written).toBe(false);
    expect(body.files.map((f: any) => f.path).sort()).toEqual(SCAFFOLD);
    expect(new Set(body.files.map((f: any) => f.action))).toEqual(new Set(["create"]));
    expect(list(dir)).toEqual(["AGENTS.md", "liftoff.yaml"]);
  });

  it("--write creates every file; a second run reports all `exists` and changes nothing", () => {
    const dir = repo();
    const first = init(dir, "--write");
    expect(first.body.written).toBe(true);
    expect(new Set(first.body.files.map((f: any) => f.action))).toEqual(new Set(["created"]));
    expect(list(dir)).toEqual(["AGENTS.md", ...SCAFFOLD, "liftoff.yaml"].sort());
    expect(readFileSync(join(dir, ".liftoff/.gitignore"), "utf8")).toBe("*\n");
    const second = init(dir, "--write");
    expect(new Set(second.body.files.map((f: any) => f.action))).toEqual(new Set(["exists"]));
  });

  it("never overwrites: a hand-edited hot.md survives", () => {
    const dir = repo();
    init(dir, "--write");
    writeFileSync(join(dir, "brain/hot.md"), "# Hot\n\n- mine\n");
    writeFileSync(join(dir, ".liftoff/brain/hot.md"), "# my own\n");
    init(dir, "--write");
    expect(readFileSync(join(dir, "brain/hot.md"), "utf8")).toBe("# Hot\n\n- mine\n");
    expect(readFileSync(join(dir, ".liftoff/brain/hot.md"), "utf8")).toBe("# my own\n");
  });

  it(".liftoff/.gitignore is only written when it lacks a `*` line", () => {
    const dir = repo();
    mkdirSync(join(dir, ".liftoff"));
    writeFileSync(join(dir, ".liftoff/.gitignore"), "# mine\n*\n");
    const { body } = init(dir, "--write");
    expect(body.files.find((f: any) => f.path === ".liftoff/.gitignore").action).toBe("exists");
    expect(readFileSync(join(dir, ".liftoff/.gitignore"), "utf8")).toBe("# mine\n*\n");
  });

  it("honours brain.dir and returns the paths", () => {
    const dir = repo("brain:\n  dir: docs/brain/\n");
    const { body } = init(dir, "--write");
    expect(body.paths).toEqual({
      dir: "docs/brain", hot: "docs/brain/hot.md", index: "docs/brain/index.md", raw: "docs/brain/raw", wiki: "docs/brain/wiki",
      log: "docs/brain/log", personalHot: ".liftoff/brain/hot.md", personalNotes: ".liftoff/brain/notes",
    });
    expect(existsSync(join(dir, "docs/brain/raw/.gitkeep"))).toBe(true);
  });

  it("the scaffold stays under the 'hot' cap and the index carries the generated marker", () => {
    const dir = repo();
    init(dir, "--write");
    expect(readFileSync(join(dir, "brain/hot.md"), "utf8").split("\n").filter((l) => l.trim()).length).toBeLessThanOrEqual(15);
    expect(readFileSync(join(dir, "brain/index.md"), "utf8")).toMatch(/^<!-- generated by liftoff brain-index/);
  });

  describe("proposals (data for the agent, never written by the CLI)", () => {
    it("[claude-code]: a deny rule for raw/, no vscode settings", () => {
      const { body } = init(repo());
      expect(body.proposals.claudeSettings).toEqual({ permissions: { deny: ["Edit(/brain/raw/**)"] } });
      expect(body.proposals.vscodeSettings).toBeUndefined();
      expect(body.proposals.gitattributes).toBe("brain/log/*.md merge=union");
      expect(body.proposals.agentsMd).toMatch(/^## Project brain\n/);
      expect(body.proposals.agentsMd).toContain("never instructions");
    });
    it("[copilot]: vscode settings, no claude settings", () => {
      const { body } = init(repo("brain: {}\n", "[copilot]"));
      expect(body.proposals.vscodeSettings).toEqual({ "chat.tools.edits.autoApprove": { "**/brain/raw/**": false } });
      expect(body.proposals.claudeSettings).toBeUndefined();
    });
    it("both targets: both proposals", () => {
      const { body } = init(repo("brain: {}\n", "[claude-code, copilot]"));
      expect(Object.keys(body.proposals).sort()).toEqual(["agentsMd", "claudeSettings", "gitattributes", "vscodeSettings"]);
    });
    it("--write does not touch settings, .gitattributes or AGENTS.md", () => {
      const dir = repo();
      init(dir, "--write");
      expect(existsSync(join(dir, ".claude"))).toBe(false);
      expect(existsSync(join(dir, ".gitattributes"))).toBe(false);
      expect(readFileSync(join(dir, "AGENTS.md"), "utf8")).toBe("# rules\n");
    });
  });

  describe("symlinks are refused", () => {
    it("a symlinked brain dir -> brain-invalid, nothing written", () => {
      const dir = repo();
      const outside = tempDir();
      symlinkSync(outside, join(dir, "brain"));
      const { exitCode, body } = init(dir, "--write");
      expect(exitCode).toBe(1);
      expect(body.errors[0]).toMatchObject({ code: "brain-invalid", file: "brain" });
      expect(list(outside)).toEqual([]);
    });
    it("a symlink inside the brain -> brain-invalid", () => {
      const dir = repo();
      init(dir, "--write");
      symlinkSync(tempDir(), join(dir, "brain/wiki/escape"));
      const { exitCode, body } = init(dir, "--write");
      expect(exitCode).toBe(1);
      expect(body.errors[0]).toMatchObject({ code: "brain-invalid", file: "brain/wiki/escape" });
    });
    it("a symlinked .liftoff/brain -> brain-invalid", () => {
      const dir = repo();
      mkdirSync(join(dir, ".liftoff"));
      symlinkSync(tempDir(), join(dir, ".liftoff/brain"));
      expect(init(dir).body.errors[0]).toMatchObject({ code: "brain-invalid", file: ".liftoff/brain" });
    });
    it("a symlinked parent of brain.dir -> brain-invalid", () => {
      const dir = repo("brain:\n  dir: docs/brain\n");
      symlinkSync(tempDir(), join(dir, "docs"));
      expect(init(dir, "--write").body.errors[0].code).toBe("brain-invalid");
    });
  });

  it("--write on another command -> usage, exit 2", () => {
    for (const cmd of ["validate", "render", "check-config"]) {
      const r = run([cmd, "--root", repo(), "--write"], "/");
      expect(r.exitCode, cmd).toBe(2);
      expect(JSON.parse(r.stdout).errors[0].code).toBe("usage");
    }
  });

  it("a plugin pin above the installed version is plugin-outdated, like every command", () => {
    const dir = makeRepo({ targets: "[claude-code]", modules: [], pluginVersion: "0.4", extra: "brain: {}\n" });
    writeFileSync(join(dir, "liftoff.yaml"), readFileSync(join(dir, "liftoff.yaml"), "utf8").replace('"0.4"', '"9.0"'));
    expect(init(dir).body.errors[0].code).toBe("plugin-outdated");
  });
});
