// The generated handbook index: one line per page. Pure, like the brain's. A stub is marked, so nobody reads it as guidance.
import { parseHandbookPage } from "./page.js";

export const HB_INDEX_MARKER = "<!-- generated by liftoff brain-index; edit page front matter instead -->";
const HEADINGS = { practice: "Practices", convention: "Conventions", case: "Cases" } as const;
const byCodeUnit = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);
const escapeLabel = (s: string): string => s.replace(/[[\]\\]/g, "\\$&");

export interface HbIndexPage { id: string; text: string }

export function buildHandbookIndex(pages: HbIndexPage[]): { content: string; skipped: { id: string; errors: string[] }[] } {
  const skipped: { id: string; errors: string[] }[] = [];
  const rows: { id: string; title: string; type: keyof typeof HEADINGS; summary: string; stub: boolean }[] = [];
  for (const p of pages) {
    const r = parseHandbookPage(p.text);
    if (r.ok) rows.push({ id: p.id, title: r.front.title, type: r.front.type, summary: r.front.summary, stub: r.front.status === "stub" });
    else skipped.push({ id: p.id, errors: r.errors });
  }
  rows.sort((a, b) => byCodeUnit(a.title.toLowerCase(), b.title.toLowerCase()) || byCodeUnit(a.id, b.id));
  skipped.sort((a, b) => byCodeUnit(a.id, b.id));
  const sections = (Object.keys(HEADINGS) as (keyof typeof HEADINGS)[]).flatMap((type) => {
    const mine = rows.filter((r) => r.type === type).map((r) => `- [${escapeLabel(r.title)}](${r.id}.md)${r.stub ? " (to fill in, not yet guidance)" : ""} - ${r.summary}`);
    return mine.length === 0 ? [] : [`## ${HEADINGS[type]}\n\n${mine.join("\n")}\n`];
  });
  const body = sections.length === 0 ? "_No pages yet._\n" : sections.join("\n");
  return { content: `${HB_INDEX_MARKER}\n\n# Handbook\n\n${body}`, skipped };
}
